import { BetterAuthError } from "@better-auth/core/error";
import type {
	ColumnDefinitionNode,
	DatabaseConnection,
	Dialect,
	Kysely,
	PostgresDialectConfig,
} from "kysely";
import {
	AddColumnNode,
	AlterTableNode,
	CompiledQuery,
	CreateIndexNode,
	CreateTableNode,
	DataTypeNode,
	PostgresDialect,
	RawNode,
} from "kysely";
import { withDsqlRetry } from "./retry";

const dsqlAdapters = new WeakSet<object>();

function columnForDsql(column: ColumnDefinitionNode): ColumnDefinitionNode {
	if (
		RawNode.is(column.dataType) &&
		column.dataType.sqlFragments.join("") ===
			"integer GENERATED BY DEFAULT AS IDENTITY"
	) {
		return {
			...column,
			dataType: RawNode.createWithSql(
				"bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1)",
			),
		};
	}
	if (
		column.references &&
		DataTypeNode.is(column.dataType) &&
		column.dataType.dataType === "integer"
	) {
		return { ...column, dataType: DataTypeNode.create("bigint") };
	}
	return column;
}

/** @internal Compose the PostgreSQL dialect without changing shared SQL code. */
export function withDsqlDialect(postgres: Dialect): Dialect {
	return {
		createAdapter() {
			const adapter = postgres.createAdapter();
			dsqlAdapters.add(adapter);
			return adapter;
		},
		createIntrospector: (db) => postgres.createIntrospector(db),
		createQueryCompiler() {
			const compiler = postgres.createQueryCompiler();
			const compile = compiler.compileQuery.bind(compiler);
			compiler.compileQuery = (node, id) => {
				if (CreateTableNode.is(node))
					node = { ...node, columns: node.columns?.map(columnForDsql) };
				if (AlterTableNode.is(node))
					node = {
						...node,
						columnAlterations: node.columnAlterations?.map((change) =>
							AddColumnNode.is(change)
								? { ...change, column: columnForDsql(change.column) }
								: change,
						),
					};
				const query = compile(node, id);
				return CreateIndexNode.is(node)
					? {
							...query,
							sql: query.sql.replace(
								/^create (unique )?index /i,
								"create $1index async ",
							),
						}
					: query;
			};
			return compiler;
		},
		createDriver() {
			const driver = postgres.createDriver();
			const acquire = driver.acquireConnection.bind(driver);
			const wrapped = new WeakSet<DatabaseConnection>();
			driver.acquireConnection = async () => {
				const connection = await acquire();
				if (!wrapped.has(connection)) {
					wrapped.add(connection);
					const execute = connection.executeQuery.bind(connection);
					connection.executeQuery = async <R>(query: CompiledQuery) => {
						const ddl = /^(create|alter|drop) /i.test(query.sql);
						const result = ddl
							? await withDsqlRetry(() => execute<R>(query))
							: await execute<R>(query);
						if (CreateIndexNode.is(query.query)) {
							const jobId = (result.rows[0] as { job_id?: string } | undefined)
								?.job_id;
							if (!jobId)
								throw new BetterAuthError(
									"Aurora DSQL did not return an index job ID.",
								);
							await waitForIndex(jobId, <T>(statement: CompiledQuery) =>
								execute<T>(statement),
							);
						}
						return result;
					};
				}
				return connection;
			};
			return driver;
		},
	};
}

/** @internal System results must bypass user Kysely result plugins. */
export async function waitForIndex(
	jobId: string,
	execute: DatabaseConnection["executeQuery"],
) {
	const result = await withDsqlRetry(() =>
		execute<{ succeeded: boolean }>(
			CompiledQuery.raw("call sys.wait_for_job($1)", [jobId]),
		),
	);
	if (result.rows[0]?.succeeded !== true)
		throw new BetterAuthError(
			`Aurora DSQL index job "${jobId}" did not complete successfully. Inspect sys.jobs before rerunning the migration.`,
		);
}

/** PostgreSQL dialect with DSQL async indexes and numeric identity definitions. */
export function dsqlDialect(config: PostgresDialectConfig): Dialect {
	return withDsqlDialect(new PostgresDialect(config));
}

/** @internal Reject a connection that would silently use synchronous DDL. */
export function assertDsqlDatabase(
	db: Pick<Kysely<unknown>, "getExecutor">,
): void {
	if (!dsqlAdapters.has(db.getExecutor().adapter))
		throw new BetterAuthError(
			"Create the Kysely database with dsqlDialect before using the DSQL adapter or migrations.",
		);
}
